async def test_fc02_website_timeout():
    lines = ["=== [FC-02] Website Timeout Test ==="]
    # Use non-routable IP to force a socket/HTTP timeout
    test_domain = "10.255.255.1"
    t0 = time.perf_counter()
    res = await fetch_website_metadata(test_domain, timeout=5.0, max_redirects=1)
    ms = int((time.perf_counter() - t0) * 1000)

    lines.append(f"Target: {test_domain}")
    lines.append(f"Latency: {ms}ms")
    lines.append(f"Reachable: {res.reachable}")
    lines.append(f"Error Code: {res.error_code}")
    lines.append(f"Error Message: {res.error_message}")

    # Verify bounded timeout: must not hang indefinitely (ceiling: <8000ms)
    bounded = ms < 8000
    lines.append(f"Bounded Timeout Enforced (<8000ms): {bounded}")
    lines.append(f"Actionable Message Provided: {bool(res.error_message)}")

    passed = (not res.reachable) and bounded and (res.error_code in ("TIMEOUT", "CONNECTION_ERROR", "ERROR"))
    lines.append(f"Test Result: {'PASS' if passed else 'FAIL'}")
    log_test_result(lines)
    return {"id": "FC-02", "name": "Website Timeout", "passed": passed, "latency_ms": ms}


