    passed = bypass_caught and (state.approval_state.status.value == "QUARANTINED") and (not state.crm_payload.metadata.dispatch_authorized) and has_audit_block
    lines.append(f"Test Result: {'PASS' if passed else 'FAIL'}")
    log_test_result(lines)
    return {"id": "FC-09", "name": "Quarantine Approval Bypass", "passed": passed, "latency_ms": ms}


